"""Parse design/screenplay.txt into numbered elements: film/script.json and film/script.js (window.FILM_SCRIPT).

  python3 tools/parse_script.py

Ids: S## scene headings (including INSERT, FLASH, FLASH CUTS and QUICK FLASH), A### action, L### dialogue
(speaker, ext such as "V.O.", text with wrapped lines joined). Transitions (FADE IN:, BACK TO SCENE, FADE OUT.) have no id.
Sequences take every line of dialogue from here by id, so nothing on screen is ever retyped.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, 'design', 'screenplay.txt')

TRANSITIONS = ('FADE IN:', 'FADE OUT.', 'THE END', 'BACK TO SCENE', 'BACK TO DANIEL', 'CUT TO:')
HEADING = re.compile(r'^(INT\.|EXT\.|INSERT\b|FLASH\b|FLASH CUTS\b|QUICK FLASH\b)')


def main():
    raw = open(SRC, encoding='utf-8').read().split('\n')
    # skip the title page: everything before FADE IN:
    start = next(i for i, l in enumerate(raw) if l.strip() == 'FADE IN:')
    lines = raw[start:]
    out, ns, na, nl = [], 0, 0, 0
    i = 0
    while i < len(lines):
        l = lines[i]; s = l.strip()
        if not s: i += 1; continue
        indent = len(l) - len(l.lstrip(' '))
        if s in TRANSITIONS:
            out.append({'type': 'transition', 'text': s}); i += 1; continue
        if indent >= 16:                                   # a speaker cue, then indented dialogue until a blank line
            m = re.match(r'^([A-Z][A-Z .\']+?)(?:\s*\(([^)]+)\))?$', s)
            speaker, ext = (m.group(1).strip(), m.group(2)) if m else (s, None)
            i += 1; text = []
            while i < len(lines) and lines[i].strip():
                text.append(lines[i].strip()); i += 1
            nl += 1
            out.append({'type': 'line', 'id': 'L%03d' % nl, 'speaker': speaker, 'ext': ext, 'text': ' '.join(text)})
            continue
        if HEADING.match(s):
            ns += 1; out.append({'type': 'scene', 'id': 'S%02d' % ns, 'text': s}); i += 1; continue
        # action: a paragraph until a blank line
        para = [s]; i += 1
        while i < len(lines) and lines[i].strip() and (len(lines[i]) - len(lines[i].lstrip(' '))) < 16:
            para.append(lines[i].strip()); i += 1
        na += 1; out.append({'type': 'action', 'id': 'A%03d' % na, 'text': ' '.join(para)})
    json.dump(out, open(os.path.join(ROOT, 'film', 'script.json'), 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    with open(os.path.join(ROOT, 'film', 'script.js'), 'w', encoding='utf-8') as f:
        f.write('/* AUTOPILOT: the screenplay as numbered elements (generated by tools/parse_script.py; do not edit). */\n')
        f.write('window.FILM_SCRIPT = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n')
    print(f'{ns} scenes, {na} actions, {nl} lines')
    for e in out:
        if e['type'] == 'line': print(f"  {e['id']} {e['speaker']}{' (' + e['ext'] + ')' if e['ext'] else ''}: {e['text']}")


if __name__ == '__main__':
    main()
