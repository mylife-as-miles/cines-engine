"""Write audio/samples.js: the recorded beds (and heartbeats) as base64 for the engine, with their dB trims and credits.
  python3 tools/samples.py [trims.json]
"""
import base64, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); A = os.path.join(HERE, '..', 'audio')
cred = json.load(open(os.path.join(A, 'credits.json')))
trims = json.load(open(sys.argv[1])) if len(sys.argv) > 1 else {}
files = {'fire': 'beds/fire.ogg', 'fire_roar': 'beds/fire_roar.ogg', 'walla': 'beds/walla.ogg', 'gas': 'beds/gas.ogg', 'siren': 'beds/siren.ogg',
         'beat': 'sfx/beat.flac', 'beat2': 'sfx/beat2.flac', 'scream': 'sfx/scream.flac', 'crash': 'sfx/crash1.flac', 'crash_glass': 'sfx/glass2.flac'}
out = {}
for k, f in files.items():
    c = cred[f.split('.')[0]]
    out[k] = dict(gain=round(trims.get(k, 0.0), 2), credit=f'"{c["title"]}" by {c["creator"]}, CC0, {c["landing"]}',
                  b64=base64.b64encode(open(os.path.join(A, f), 'rb').read()).decode())
with open(os.path.join(A, 'samples.js'), 'w') as fh:
    fh.write('/* CC0 recordings for the sound engine\'s beds (generated by tools/samples.py; credits in audio/CREDITS.md) */\nwindow.FILM_AUDIO = ' + json.dumps(out) + ';\n')
print({k: v['gain'] for k, v in out.items()}, os.path.getsize(os.path.join(A, 'samples.js')) // 1024, 'KB')
