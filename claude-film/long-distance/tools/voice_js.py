"""Bundle the chosen takes for the development player: audio/voice.js (window.FILM_VOICES).

  python3 tools/voice_js.py

Reads audio/vo/voice_map.json and writes {id: {take, dur, as, b64}} with each take as base64 OGG Vorbis (mono, 32 kHz,
about q3), so the player and tools can time subtitles to the takes and play them without a server. Run it again
whenever a take changes.
"""
import base64, json, os, subprocess, tempfile

ROOT = os.path.join(os.path.dirname(__file__), '..')


def main():
    vmap = json.load(open(os.path.join(ROOT, 'audio/vo/voice_map.json')))
    out, tmp = {}, tempfile.mkdtemp()
    for lid, v in vmap.items():
        ogg = os.path.join(tmp, lid + '.ogg')
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', os.path.join(ROOT, v['file']), '-ac', '1', '-ar', '32000',
                        '-c:a', 'libvorbis', '-q:a', '3', ogg], check=True)
        out[lid] = {'take': v['take'], 'dur': v['dur'], 'as': v['as'], 'b64': base64.b64encode(open(ogg, 'rb').read()).decode()}
    head = ('/* The recorded takes for the development player, keyed by script line id (generated by tools/voice_js.py from\n'
            '   audio/vo/voice_map.json; Gemini TTS, see design/DECISIONS.md). dur is the trimmed take length in seconds; as is the\n'
            '   treatment the mix gives the line (phone, door, room, bed). */\n')
    open(os.path.join(ROOT, 'audio/voice.js'), 'w').write(head + 'window.FILM_VOICES = ' + json.dumps(out) + ';\n')
    print('audio/voice.js:', len(out), 'takes,', os.path.getsize(os.path.join(ROOT, 'audio/voice.js')) // 1024, 'KB')


if __name__ == '__main__':
    main()
