def pick_choir(arg):
    if arg:
        p = arg if os.path.isabs(arg) else os.path.join(os.getcwd(), arg)
        if not os.path.isfile(p):
            p = os.path.join(ROOT, arg)
        return p if os.path.isfile(p) else None
    for name in CHOIR_PICK:
        p = asset_path(name, CHOIRS)
        if p:
            return p
    if os.path.isdir(CHOIRS):
        for fn in sorted(os.listdir(CHOIRS)):
            if fn.endswith(('.flac', '.wav')):
                return os.path.join(CHOIRS, fn)
    return None


def build_choir(path, offset):
    """the choir from CHOIR_IN to CHOIR_OUT: one continuous, non-looping stretch of the chosen file"""
    need = CHOIR_OUT - CHOIR_IN + 0.2
    if path:
        x = st(read_audio(path))
        if len(x) / SR < offset + need:
            offset = max(0.0, len(x) / SR - need)
        x = x[int(offset * SR):int((offset + need) * SR)]
        label = f"{os.path.relpath(path, ROOT)} {offset:g}-{offset + need:.1f} s (one pass, not looped)"
        t0 = CHOIR_IN
    else:                                                        # stand-in: the old phrase ONCE, over the seal only
        WARN.append("MX-01: no choir in audio/choir; stand-in: the old phrase (Q02_t1 0-6.9 s) once, 17.4-24.25 only")
        x = st(tk('Q02_t1', 0.0, 6.85))
        label = "out/takes/Q02_t1.mp4 0-6.85 s (the old phrase, once, not looped)"
        t0 = CHOIR_OUT - 6.85
    x = eq(x, CHOIR_EQ)
    full, under = np.zeros((N, 2)), np.zeros((N, 2))
    place(full, x, t0)
    place(under, eq(x, CHOIR_UNDER_EQ), t0)
    env = auto(CHOIR_ENV)
    # how far it is "under": 1 while anyone speaks, 0 once it has opened
    u = auto([(0, None), (13.8, None), (14.25, 0.0), (18.6, 0.0), (19.3, None), (DUR, None)])
    y = (under * u[:, None] + full * (1 - u[:, None])) * env[:, None]
    seg = y[int(19.3 * SR):int(CHOIR_OUT * SR)]
    y *= lin(CHOIR_OPEN - lvl(seg, 'm'))
    return y, label


