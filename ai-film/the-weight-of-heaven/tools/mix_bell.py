def render_simple(c):
    """a simple cue -> (dry (N,2), send (N,2) or None, source label, level as placed, standin?)"""
    if c.get('only_if_missing') and asset_path(c['only_if_missing']):
        return None
    x, sync, label, standin = resolve(c)
    if x is None:
        return None
    x = np.asarray(x, np.float64)
    if c.get('speed'):
        x = varispeed(x, c['speed'])
        sync = sync / c['speed']
        label += f", varispeed x{c['speed']:g}"
    if c.get('maxlen'):
        x = x[:int(c['maxlen'] * SR)]
    if 'pan' in c or 'width' in c:
        x = mono(x)
    x = eq(x, c.get('eq'))
    x = fade(x, c.get('fi', 0.003), c.get('fo', 0.02))
    x = widen(x, c['width'], zlib.crc32(c['id'].encode()) % 1000) if 'width' in c else pan(x, c['pan']) if 'pan' in c else st(x)
    if c.get('mode') == 'peak':                                  # short transients are set by their sample peak (dBFS)
        x = x * lin(c['lvl']) / np.abs(x).max()
    else:
        x = x * lin(c['lvl'] - lvl(x, c.get('mode', 'pk')))
    dry = np.zeros((N, 2))
    place(dry, x, c['t'] - sync)
    for a, b in c.get('mute', []):                               # holes with 25 ms edges (events lifted out)
        k = int(0.025 * SR)
        i, j = int(a * SR), int(b * SR)
        g = np.ones(N)
        g[i:j] = 0
        g[i - k:i] = ramp(k, False)
        g[j:j + k] = ramp(k)
        dry *= g[:, None]
    send = dry * lin(c['send']) if c.get('send') is not None else None
    return dry, send, label, standin


