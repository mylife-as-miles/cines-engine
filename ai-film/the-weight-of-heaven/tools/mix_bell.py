def resolve(cue):
    """the first available source of a cue -> (audio, sync seconds, label, is_standin)"""
    for k, s in enumerate(cue['src']):
        got = s.get()
        if got is not None:
            if k > 0 and isinstance(cue['src'][0], A):
                WARN.append(f"{cue['id']}: asset '{cue['src'][0].name}' is missing; using stand-in ({got[2]})")
            return (*got, k > 0 and isinstance(cue['src'][0], A))
    names = ', '.join(getattr(s, 'name', '?') for s in cue['src'])
    WARN.append(f"{cue['id']}: SKIPPED, no source available ({names})")
    return None, 0.0, 'missing', True


# ------------------------------------------------------------------------------------------ numpy stand-ins
def _noise_band(n, seed, lo, hi, tilt=0.0, ch=1):
    """noise shaped in the frequency domain: a band lo..hi with `tilt` dB per octave"""
    rng = np.random.default_rng(seed)
    f = np.fft.rfftfreq(n, 1 / SR)
    g = (np.maximum(f, 1.0) / 1000.0) ** (tilt / 6.0206)
    g *= 1 / np.sqrt(1 + (lo / np.maximum(f, 1e-6)) ** 6) / np.sqrt(1 + (f / hi) ** 6)
    out = [np.fft.irfft(np.fft.rfft(rng.standard_normal(n)) * g, n) for _ in range(ch)]
    y = np.stack(out, 1) if ch > 1 else out[0]
    return y / np.sqrt((y ** 2).mean())


def _slow(n, seed, rate, depth_db):
    """a slow random gain curve (dB swing of about +-depth) wandering at about `rate` Hz"""
    rng = np.random.default_rng(seed)
    k = max(int(n / SR * rate * 4) + 4, 8)
    pts = rng.standard_normal(k)
    pts = np.convolve(pts, [0.25, 0.5, 0.25], 'same')
    c = np.interp(np.linspace(0, k - 1, n), np.arange(k), pts)
    c = ndimage.uniform_filter1d(c, int(SR / rate / 4))
    return lin(depth_db * c / max(np.abs(c).max(), 1e-9))


def _whistle(n, seed, f_lo, f_hi, bw=0.05, rate=0.12):
    """narrow-band noise whose centre glides slowly between f_lo and f_hi (stereo, unit RMS): wind in a gap"""
    rng = np.random.default_rng(seed)
    out = np.zeros((n, 2))
    for ch in range(2):
        k = max(int(n / SR * rate * 4) + 4, 8)
        c = np.interp(np.linspace(0, k - 1, n), np.arange(k), rng.uniform(0, 1, k))
        fc = f_lo * (f_hi / f_lo) ** ndimage.uniform_filter1d(c, int(SR / rate / 3))
        z = signal.sosfilt(signal.butter(2, np.median(fc) * bw, 'lowpass', fs=SR, output='sos'),
                           rng.standard_normal(n) + 1j * rng.standard_normal(n))
        out[:, ch] = np.real(z * np.exp(2j * np.pi * np.cumsum(fc) / SR))
    return out / np.sqrt((out ** 2).mean())


def syn_hall(length=7.5, predelay=0.100, seed=7):
    """a synthetic cathedral impulse response: wet only, pre-delayed, RT60 about 6.5 s falling to 1.5 s at 8 kHz"""
    rng = np.random.default_rng(seed)
    n = int(length * SR)
    t = np.arange(n) / SR
    f = np.fft.rfftfreq(n, 1 / SR)
    bands = [(0, 180, 6.0, 0.9), (180, 360, 7.0, 1.0), (360, 720, 6.8, 1.0), (720, 1400, 6.0, 0.9),
             (1400, 2800, 4.8, 0.75), (2800, 5600, 3.2, 0.55), (5600, 11000, 1.8, 0.35), (11000, 24000, 1.0, 0.2)]
    y = np.zeros((n, 2))
    for ch in range(2):
        W = np.fft.rfft(rng.standard_normal(n))
        for lo, hi, rt, g in bands:
            m = ((f >= lo) & (f < hi)).astype(float)
            y[:, ch] += g * np.fft.irfft(W * m, n) * 10 ** (-3 * t / rt)
        y[:, ch] *= 1 - np.exp(-t / 0.045)
        for _ in range(14):                                      # early reflections off the arcades
            d, a = rng.uniform(0.012, 0.16), rng.uniform(0.2, 0.6) * rng.choice([-1, 1])
            y[int(d * SR), ch] += a * np.sqrt((y[:, ch] ** 2).sum()) * 0.05 * np.exp(-d / 0.08)
    y = np.concatenate([np.zeros((int(predelay * SR), 2)), y])[:n]
    y = fade(y, 0, 0.5)
    return y / np.sqrt((y ** 2).sum(0).mean())


def syn_wind(dur=40.0, seed=11):
    """open high air: wide noise with a slow moan around 300-1000 Hz and real air at 2-10 kHz"""
    n = int(dur * SR)
    y = 1.0 * _noise_band(n, seed, 70, 11000, -4.0, 2)
    for k, (fc, g) in enumerate([(280, 0.5), (460, 0.45), (780, 0.4), (1200, 0.3)]):
        b = _noise_band(n, seed + 10 + k, fc / 1.25, fc * 1.25, 0.0, 2)
        y += g * b * _slow(n, seed + 20 + k, 0.12, 5.0)[:, None]
    y += 0.22 * _noise_band(n, seed + 40, 2000, 10000, -2.0, 2) * _slow(n, seed + 41, 0.5, 3.0)[:, None]
    return y / np.sqrt((y ** 2).mean())


def syn_crowd(dur=36.3, seed=21):
    """thousands standing still in a stone hall: a soft wide murmur of air and cloth, no voices"""
    n = int(dur * SR)
    y = _noise_band(n, seed, 110, 2200, -5.0, 2) * _slow(n, seed + 1, 0.2, 2.0)[:, None]
    rng = np.random.default_rng(seed + 2)
    ev = np.zeros((n, 2))
    for _ in range(int(dur * 2.2)):                              # sparse soft shifts of cloth, each somewhere else
        d = int(rng.uniform(0.08, 0.3) * SR)
        i = rng.integers(0, n - d)
        b = _noise_band(d, int(rng.integers(1 << 30)), 350, 3200, -6.0) * np.hanning(d) ** 2
        p = rng.uniform(-0.9, 0.9)
        ev[i:i + d] += pan(b, p) * lin(rng.uniform(-8, 0))
    y += 0.35 * ev
    return y / np.sqrt((y ** 2).mean())


def syn_paper(dur=0.8, seed=31, moves=((0.15, 0.25), (0.5, 0.35))):
    """heavy parchment handled: bursts of tiny crackle grains over a soft sheet body"""
    n = int(dur * SR)
    rng = np.random.default_rng(seed)
    t = np.arange(n) / SR
    env = sum(np.exp(-0.5 * ((t - c * dur) / (w * dur / 2.5)) ** 2) for c, w in moves)
    y = np.zeros(n)
    for _ in range(int(260 * dur)):
        i = int(rng.choice(n, p=env / env.sum()))
        d = int(rng.uniform(0.0015, 0.007) * SR)
        fc = np.exp(rng.uniform(np.log(1500), np.log(8500)))
        g = np.sin(2 * np.pi * fc * np.arange(d) / SR + rng.uniform(0, 6.28)) * rng.standard_normal(d) * np.exp(-np.arange(d) / (d / 3))
        j = min(i + d, n)
        y[i:j] += g[:j - i] * rng.lognormal(0, 0.6)
    body = _noise_band(n, seed + 1, 300, 1800, -3.0) * env
    y = y / max(np.abs(y).max(), 1e-9) + 0.25 * body / max(np.abs(body).max(), 1e-9)
    return fade(y, 0.005, 0.05)


def syn_cloth(dur=0.7, seed=41):
    """a heavy sleeve moving: one soft swell of fabric friction"""
    n = int(dur * SR)
    t = np.arange(n) / SR
    env = np.sin(np.pi * np.clip(t / dur, 0, 1)) ** 1.5
    tex = 0.6 + 0.4 * np.abs(_noise_band(n, seed + 1, 12, 55))
    return fade(_noise_band(n, seed, 280, 4200, -6.0) * env * tex, 0.01, 0.05)


def syn_press(seed=51):
    """a signet pressed into soft wax, close: a small soft thup with a little tack"""
    n = int(0.22 * SR)
    t = np.arange(n) / SR
    rng = np.random.default_rng(seed)
    thup = np.sin(2 * np.pi * (140 * t + 60 * 0.03 * (1 - np.exp(-t / 0.03)))) * np.exp(-t / 0.03) * (1 - np.exp(-t / 0.002))
    sq = eq(rng.standard_normal(n), [('hp', 500), ('lp', 3500)]) * np.exp(-t / 0.045) * (1 - np.exp(-t / 0.006))
    return fade(thup + 0.5 * sq / np.abs(sq).max(), 0.001, 0.03)


def syn_lift(seed=52):
    """the ring peels off the wax: one tiny tacky tick"""
    n = int(0.09 * SR)
    t = np.arange(n) / SR
    rng = np.random.default_rng(seed)
    y = eq(rng.standard_normal(n), [('hp', 1500), ('lp', 7000)]) * (np.exp(-t / 0.006) + 0.5 * np.exp(-((t - 0.03) / 0.004) ** 2))
    return fade(y, 0.0005, 0.02)


def syn_whoosh(dur=0.62, seed=61):
    """a door-sized mass swinging: low noise whose band opens toward the end, then stops (the stroke takes over)"""
    n = int(dur * SR)
    t = np.arange(n) / SR
    y = np.zeros(n)
    for k, fc in enumerate([60, 95, 150, 230, 350, 520, 800]):
        b = _noise_band(n, seed + k, fc / 1.3, fc * 1.3)
        u = np.clip(t / (dur * 0.68) - 0.08 * k, 0, 1)
        y += b * u ** 2.2 * (0.9 ** k)
    y *= np.where(t <= dur * 0.68, 1.0, np.exp(-(t - dur * 0.68) / 0.07))
    return fade(y, 0.02, 0.03)


def syn_thud(seed=71):
    """a colossal weight taken by stone and timber: a sub drop, a body of low noise, a short timber groan"""
    n = int(1.6 * SR)
    t = np.arange(n) / SR
    rng = np.random.default_rng(seed)
    f = 36 + 30 * np.exp(-t / 0.05)
    sub = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.26) * (1 - np.exp(-t / 0.006))
    body = eq(rng.standard_normal(n), [('lp', 260, 4)]) * np.exp(-t / 0.07) * (1 - np.exp(-t / 0.003))
    gr = np.sign(np.sin(2 * np.pi * np.cumsum(62 - 14 * t / 1.6 + 5 * np.sin(2 * np.pi * 3.1 * t)) / SR))
    groan = eq(gr, [('hp', 70), ('lp', 420, 4)]) * np.exp(-((t - 0.45) / 0.3) ** 2) * (0.6 + 0.4 * np.abs(_noise_band(n, seed + 1, 8, 30)))
    return fade(sub + 0.7 * body / np.abs(body).max() + 0.12 * groan / np.abs(groan).max(), 0.001, 0.2)


def syn_grit(dur=1.0, seed=81):
    """dust and grit falling onto bronze: sparse ticks thinning out, a breath of hiss"""
    n = int(dur * SR)
    rng = np.random.default_rng(seed)
    t = np.arange(n) / SR
    y = np.zeros((n, 2))
    dens = np.exp(-t / (dur * 0.35)) * (1 - np.exp(-t / 0.05))
    for ch in range(2):
        imp = (rng.random(n) < dens * 320 / SR) * rng.lognormal(0, 0.8, n)
        k = int(0.004 * SR)
        ker = np.sin(2 * np.pi * 5200 * np.arange(k) / SR) * np.exp(-np.arange(k) / (k / 4))
        y[:, ch] = signal.fftconvolve(imp, ker)[:n] + 0.25 * _noise_band(n, seed + 3 + ch, 3500, 10000) * dens * 0.1
    return fade(y, 0.002, 0.1)


def syn_bell_body(f_main=191.7, dur=22.0, seed=48):
    """the low body of the bell if the foundry's is missing: hum and prime two and one octaves under the stroke"""
    n = int(dur * SR)
    t = np.arange(n) / SR
    rng = np.random.default_rng(seed)
    y = np.zeros((n, 2))
    for f, g, t60, split in ((f_main / 4, 0.0, 20.0, 0.21), (f_main / 2, 0.0, 17.0, 0.34), (f_main, -12.0, 11.0, 0.5)):
        env = np.exp(-6.908 * t / t60) * (1 - np.exp(-t / 0.05))
        for sgn, a, p in ((-1, 1.0, -0.22), (1, 0.4, 0.22)):
            s = lin(g) * a * env * np.sin(2 * np.pi * (f + sgn * split / 2) * t + rng.uniform(0, 6.28))
            y += pan(s, p) / np.sqrt(2)
    return fade(y, 0.002, 1.5)


# ------------------------------------------------------------------------------------------ the bell
# One bell, built once and struck twice. What reads as a bell (earshot, forced choice against a gong and a cinematic
# boom) is a sparse partial series with a strong prime, minor third, nominal and twelfth; what reads as a gong or a
# "cinematic hit" is the take's own stroke (a dense cluster at 165-350 Hz and a noisy transient) and too much sub.
# So: the RING is a cast church bell tuned so its prime sits on the take's main partial (191.6 Hz; its hum is then
# 95.8 Hz), the foundry's bell_body adds the octave under that (47.9 Hz) and weight at 95.9 Hz, the take's own strike
# stays as the hammer's contact, short and low, and the strike pitched down adds mass on the hit only.
# Levels are dB against the ring (RMS of its first second).
BELL = dict(
    ring_prime_hz=392.0,  # the earshot church bell is a G4 bell: prime 392 Hz (measured again at build time)
    body_db=-8.0,         # bell_body (47.9 and 95.9 Hz): RMS of its first second
    take_db=-15.0,        # the take's own strike: RMS of its first 250 ms (louder, both witnesses hear a hit or a braam)
    clang_db=-7.0,        # the hammer's clang: the bell's own upper partials an octave up (RMS of its first 250 ms)
    clang_tau=0.15,       # ... dying with this time constant (s)
    take_hp=170.0,        # it keeps 172/192 Hz and up; its 83 and 110 Hz would beat against the 96 Hz hum
    take_lp=3500.0,
    take_hold=0.18,       # whole for this long, then it falls away (its own ring is the gong-like cluster)
    take_len=1.4,
    oct1_db=-17.0,        # the strike an octave down, short: mass on the hit
    oct2_db=-22.0,        # and two octaves down
    # fallback only, if neither a foundry bell_ring nor earshot is there: (ratio to the prime, dB, T60 s)
    series=((0.5, -8, 40.0), (1.0, -3, 30.0), (1.18, 0, 20.0), (1.505, -14, 15.0), (2.0, 2, 14.0), (2.51, -20, 9.0),
            (2.66, -24, 9.0), (3.005, -3, 8.8), (4.16, -11, 4.5), (5.43, -15, 2.9), (6.79, -28, 2.0)),
)


def main_partial(m, t_on, fmin=150.0, fmax=3000.0):
    """the strongest partial of a stroke over its first second (Hz)"""
    a, L = int((t_on + 0.10) * SR), SR
    w = np.hanning(L)
    X = np.abs(np.fft.rfft(m[a:a + L] * w, 8 * L))
    f = np.fft.rfftfreq(8 * L, 1 / SR)
    sel = (f > fmin) & (f < fmax)
    return float(f[sel][np.argmax(X[sel])])


def syn_bell_series(f_prime=191.6, dur=20.0, seed=192):
    """a bell's partials as decaying doublets (numpy fallback for the ring)"""
    n = int(dur * SR)
    t = np.arange(n) / SR
    rng = np.random.default_rng(seed)
    y = np.zeros((n, 2))
    for ratio, g, t60 in BELL['series']:
        f = f_prime * ratio
        env = lin(g) * np.exp(-6.908 * t / t60) * (1 - np.exp(-t / (0.002 + 0.004 / ratio)))
        split = (0.12 + 0.22 * rng.random()) * ratio ** 0.7
        p = rng.uniform(0.12, 0.3) * rng.choice([-1, 1])
        y += pan(env * np.cos(2 * np.pi * (f - split / 2) * t + rng.uniform(0, 6.28)), -p) / np.sqrt(2)
        y += pan(0.45 * env * np.cos(2 * np.pi * (f + split / 2) * t + rng.uniform(0, 6.28)), p) / np.sqrt(2)
    return y


def build_bell():
    """the bell stroke as layers on one clock (index 0 = 12 ms before the take's onset). Returns (stereo, sync s,
    f_main, a description of the layers); `sync` is where the EDL's stroke frame falls."""
    key = 'bell'
    if key in _cache:
        return _cache[key]
    B = BELL
    pre = 0.012
    i0 = int(pre * SR)
    t_a = Q2B_ONSET - pre
    src = take('Q02B_t1').mean(1)
    f_main = main_partial(src, Q2B_ONSET)
    n = int(24.0 * SR)
    out = np.zeros((n, 2))
    # the ring
    cue = {'id': 'BELL-ring', 'src': [A('bell_ring', sync=0.0), ES('note/church_bell', dur=8.0),
                                      SY(syn_bell_series, 'a sparse bell partial series (decaying doublets)', f_prime=f_main)]}
    ring, _, ring_label, _ = resolve(cue)
    ring = st(ring)
    ring_src, ratio = ring, 1.0
    if ring_label.startswith('earshot'):                              # tune it: its prime onto the take's main partial
        Xr = np.abs(np.fft.rfft(mono(ring)[:4 * SR] * np.hanning(min(4 * SR, len(ring)))))
        fr = np.fft.rfftfreq(min(4 * SR, len(ring)), 1 / SR)
        sel = (fr > B['ring_prime_hz'] * 0.96) & (fr < B['ring_prime_hz'] * 1.04)
        f_src = float(fr[sel][np.argmax(Xr[sel])])
        ratio = f_main * 2.0 ** B.get('ring_octave', 0) / f_src
        ring = varispeed(ring, ratio)
        fp = f_main * 2.0 ** B.get('ring_octave', 0)
        ring_label += f", varispeed x{ratio:.3f} (prime {f_src:.1f} -> {fp:.1f} Hz, hum {fp / 2:.1f} Hz)"
    elif not ring_label.startswith('audio/sfx'):
        WARN.append("BELL: no bell_ring asset and no earshot: the ring is the numpy partial series (it reads as a gong to earshot)")
    ring = fade(ring[:n - i0], 0.001, 1.5)
    ring_rms = np.sqrt((ring[:SR] ** 2).mean(1).mean() * 2)
    ring = ring / ring_rms
    out[i0:i0 + len(ring)] += ring
    # the clang of the hammer on bronze: the same bell's upper partials, an octave up, dying in a quarter of a second
    if ring_label.startswith('earshot') and B.get('clang_db', -80) > -60:
        cl = eq(varispeed(st(ring_src), ratio * 2.0), [('hp', 500, 2)])[:int(1.2 * SR)]
        tcl = np.arange(len(cl)) / SR
        cl = cl * np.exp(-tcl / B.get('clang_tau', 0.10))[:, None]
        cl = fade(cl, 0.0005, 0.2) * lin(B['clang_db']) / np.sqrt((cl[:SR // 4] ** 2).mean(1).mean() * 2)
        out[i0:i0 + len(cl)] += cl
    # the body: the octave under the hum
    cue = {'id': 'BELL-body', 'src': [A('bell_body', sync=0.0), SY(syn_bell_body, 'hum and prime doublets', f_main=f_main)]}
    body, _, body_label, _ = resolve(cue)
    body = st(body)[:n - i0]
    body = body * lin(B['body_db']) / np.sqrt((body[:SR] ** 2).mean(1).mean() * 2)
    out[i0:i0 + len(body)] += body
    # the take's own strike: the hammer on bronze
    a = int(round(t_a * SR))
    n_take = int(B['take_len'] * SR)
    tt = np.arange(n_take) / SR
    hold = pre + B['take_hold']
    shape = np.where(tt < hold, 1.0, np.exp(-(tt - hold) / 0.25) * (0.5 + 0.5 * np.cos(np.pi * np.clip((tt - hold) / (B['take_len'] - hold), 0, 1))))
    hit = eq(fade(src[a:a + n_take], 0.008, 0) * shape, [('hp', B['take_hp'], 4), ('lp', B['take_lp'], 2)])
    hit = hit * lin(B['take_db']) / np.sqrt((hit[:SR // 4] ** 2).mean())
    out[:n_take] += st(hit)
    # the strike one and two octaves down: mass on the hit
    raw = fade(src[a:a + int(2.5 * SR)], 0.008, 0.9)
    for ratio, g, hold_s, lp in ((0.5, B['oct1_db'], 1.6, 500), (0.25, B['oct2_db'], 2.4, 240)):
        o = varispeed(raw, ratio)
        o = fade(eq(o, [('hp', 26), ('lp', lp, 4)])[:int(hold_s * SR)], 0.004, hold_s * 0.7)
        o = o * lin(g) / np.sqrt((o[:SR] ** 2).mean())
        out[:len(o)] += st(o)
    desc = {'f_main_hz': round(f_main, 1), 'ring': ring_label, 'body': body_label,
            'layers_db': {k: v for k, v in B.items() if k.endswith('_db')}}
    _cache[key] = (out, Q2B_STROKE - t_a, f_main, desc)
    return _cache[key]


def bell_stroke(target_m, darker=False):
    """one stroke of the bell at a level (its loudest 400 ms, LUFS), ready to place"""
    x, sync, _, _ = build_bell()
    y = eq(x, [('hp', 45, 2), ('ls', 140, -4.0)]) if darker else x.copy()   # the smaller stroke: the same ring, less of the sub
    y *= lin(target_m - lvl(y[:int(1.5 * SR)], 'm'))
    return y, sync


