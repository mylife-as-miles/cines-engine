def asset_path(name, folder=SFX):
    for ext in ('.flac', '.wav'):
        p = os.path.join(folder, name + ext)
        if os.path.isfile(p):
            return p
    return None


def read_audio(path):
    x, sr = sf.read(path, always_2d=True, dtype='float64')
    if sr != SR:
        fr = Fraction(SR, sr)
        x = signal.resample_poly(x, fr.numerator, fr.denominator, axis=0)
    return x


class A:
    """a foundry sound in audio/sfx. sync: 'onset' (the files are trimmed 3 ms before their onset), 'peak' (its
    loudest moment, from the manifest) or seconds into the file; a..b picks an excerpt (seconds)."""

    def __init__(self, name, a=None, b=None, sync='onset'):
        self.name, self.a, self.b, self.sync = name, a, b, sync

    def get(self):
        p = asset_path(self.name)
        if not p:
            return None
        x = read_audio(p)
        a = self.a or 0.0
        if self.sync == 'onset':
            s = a + 0.003
        elif self.sync == 'peak':                                 # the loudest 20 ms of the excerpt
            e = _slide((x[int(a * SR):int(self.b * SR) if self.b else None] ** 2).mean(1), int(0.02 * SR))
            s = a + (int(np.argmax(e)) + int(0.01 * SR)) / SR
        else:
            s = float(self.sync)
        x = x[int(a * SR):int(self.b * SR) if self.b else None]
        lic = manifest().get(self.name, {}).get('how', {}).get('method', 'foundry')
        ex = f" {a:g}-{self.b:g} s" if self.b else f" from {a:g} s" if a else ''
        return x, s - a, f"audio/sfx/{os.path.basename(p)}{ex} ({lic})"


class TK:
    """an excerpt of a take's production sound; sync = source time that lands on the cue's t (default: a)"""

    def __init__(self, name, a, b, sync=None):
        self.name, self.a, self.b, self.sync = name, a, b, a if sync is None else sync

    def get(self):
        return tk(self.name, self.a, self.b), self.sync - self.a, f"out/takes/{self.name}.mp4 {self.a:g}-{self.b:g} s"


