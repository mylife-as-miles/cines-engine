# ------------------------------------------------------------------------------------------ small DSP helpers
def db(v):
    return 20 * np.log10(np.maximum(np.abs(v), 1e-12))


def lin(d):
    return 10 ** (d / 20)


def st(x):
    x = np.asarray(x, np.float64)
    if x.ndim == 2 and x.shape[1] == 1:
        x = x[:, 0]
    return np.stack([x, x], 1) if x.ndim == 1 else x


def mono(x):
    x = np.asarray(x, np.float64)
    return x if x.ndim == 1 else x.mean(1)


def ramp(n, up=True):
    r = 0.5 - 0.5 * np.cos(np.pi * (np.arange(n) + 0.5) / max(n, 1))
    return r if up else r[::-1]


def fade(x, fin=0.0, fout=0.0):
    y = np.array(x, np.float64)
    a, b = min(int(fin * SR), len(y)), min(int(fout * SR), len(y))
    sh = (slice(None), None) if y.ndim == 2 else (slice(None),)
    if a:
        y[:a] *= ramp(a)[sh]
    if b:
        y[len(y) - b:] *= ramp(b, False)[sh]
    return y


def _rbj(kind, f, g=0.0, q=0.707):
    A, w = 10 ** (g / 40), 2 * np.pi * f / SR
    cw, sw = np.cos(w), np.sin(w)
    al = sw / (2 * q)
    if kind == 'pk':
        b, a = [1 + al * A, -2 * cw, 1 - al * A], [1 + al / A, -2 * cw, 1 - al / A]
    elif kind == 'ls':
        k = 2 * np.sqrt(A) * al
        b = [A * ((A + 1) - (A - 1) * cw + k), 2 * A * ((A - 1) - (A + 1) * cw), A * ((A + 1) - (A - 1) * cw - k)]
        a = [(A + 1) + (A - 1) * cw + k, -2 * ((A - 1) + (A + 1) * cw), (A + 1) + (A - 1) * cw - k]
    else:                                                       # 'hs'
        k = 2 * np.sqrt(A) * al
        b = [A * ((A + 1) + (A - 1) * cw + k), -2 * A * ((A - 1) + (A + 1) * cw), A * ((A + 1) + (A - 1) * cw - k)]
        a = [(A + 1) - (A - 1) * cw + k, 2 * ((A - 1) - (A + 1) * cw), (A + 1) - (A - 1) * cw - k]
    return np.array([[b[0] / a[0], b[1] / a[0], b[2] / a[0], 1.0, a[1] / a[0], a[2] / a[0]]])


def eq(x, chain):
    """chain: ('hp', f[, order]) ('lp', f[, order]) ('pk', f, gain_dB, q) ('ls', f, gain_dB) ('hs', f, gain_dB)
    ('notch', f, q). Causal, minimum phase."""
    if not chain:
        return x
    rows = []
    for c in chain:
        k = c[0]
        if k in ('hp', 'lp'):
            rows.append(signal.butter(c[2] if len(c) > 2 else 2, c[1], 'highpass' if k == 'hp' else 'lowpass',
                                      fs=SR, output='sos'))
        elif k == 'pk':
            rows.append(_rbj('pk', c[1], c[2], c[3] if len(c) > 3 else 1.0))
        elif k in ('ls', 'hs'):
            rows.append(_rbj(k, c[1], c[2]))
        elif k == 'notch':
            b, a = signal.iirnotch(c[1], c[2] if len(c) > 2 else 8, fs=SR)
            rows.append(signal.tf2sos(b, a))
        else:
            raise ValueError(k)
    return signal.sosfilt(np.vstack(rows), x, axis=0)


def eq_text(chain):
    out = []
    for c in chain or []:
        if c[0] in ('hp', 'lp'):
            out.append(f"{c[0].upper()} {c[1]:g} Hz")
        elif c[0] == 'pk':
            out.append(f"{c[2]:+g} dB at {c[1]:g} Hz")
        elif c[0] in ('ls', 'hs'):
            out.append(f"{'low' if c[0] == 'ls' else 'high'} shelf {c[2]:+g} dB at {c[1]:g} Hz")
        elif c[0] == 'notch':
            out.append(f"notch {c[1]:g} Hz")
    return ', '.join(out) or 'flat'


def varispeed(x, ratio):
    """tape speed: ratio 0.5 plays an octave lower and twice as long"""
    fr = Fraction(1 / ratio).limit_denominator(64)
    return signal.resample_poly(x, fr.numerator, fr.denominator, axis=0)


def pan(x, p):
    """mono -> stereo, constant power, p from -1 (left) to +1 (right)"""
    a = (p + 1) * np.pi / 4
    m = mono(x)
    return np.stack([m * np.cos(a), m * np.sin(a)], 1) * np.sqrt(2)


def widen(x, amount, seed):
    """mono -> wide stereo: a decorrelated copy (30 ms of decaying sparse noise, above 200 Hz) goes to the sides"""
    m = mono(x)
    rng = np.random.default_rng(seed)
    k = int(0.03 * SR)
    v = np.zeros(k)
    idx = rng.choice(np.arange(48, k), 40, replace=False)
    v[idx] = rng.choice([-1.0, 1.0], 40) * np.exp(-idx / (0.012 * SR))
    s = signal.fftconvolve(m, v)[:len(m)]
    s = eq(s, [('hp', 200)])
    s *= np.sqrt((m ** 2).mean() / max((s ** 2).mean(), 1e-20))
    y = np.stack([m + amount * s, m - amount * s], 1)
    return y / np.sqrt(1 + amount ** 2)


def auto(points, n=N):
    """a gain curve over the timeline from [(t, dB or None), ...]: raised-cosine between the points"""
    ts = np.array([p[0] for p in points], float)
    g = np.array([0.0 if p[1] is None else lin(p[1]) for p in points])
    t = np.arange(n) / SR
    i = np.clip(np.searchsorted(ts, t, 'right') - 1, 0, len(ts) - 2)
    u = np.clip((t - ts[i]) / np.maximum(ts[i + 1] - ts[i], 1e-9), 0, 1)
    return g[i] + (g[i + 1] - g[i]) * (0.5 - 0.5 * np.cos(np.pi * u))


def place(dst, x, t):
    """add x (n, 2) into dst so that x[0] falls at timeline t"""
    i = int(round(t * SR))
    a, b = max(i, 0), min(i + len(x), len(dst))
    if b > a:
        dst[a:b] += x[a - i:b - i]


# ------------------------------------------------------------------------------------------ meters (BS.1770)
_KSOS = np.array([[1.53512485958697, -2.69169618940638, 1.19839281085285, 1.0, -1.69065929318241, 0.73248077421585],
                  [1.0, -2.0, 1.0, 1.0, -1.99004745483398, 0.99007225036621]])


def kpow(x):
    return (signal.sosfilt(_KSOS, st(x), axis=0) ** 2).sum(1)


def _slide(p, win):
    """mean of p over every window of `win` samples (ending at each sample)"""
    c = np.concatenate([[0.0], np.cumsum(p)])
    w = min(win, len(p))
    return (c[w:] - c[:-w]) / w


def lvl(x, mode='pk'):
    """K-weighted level in LUFS: 'm' loudest 400 ms, 'pk' loudest 100 ms, 'rms' the whole signal"""
    p = kpow(x)
    if mode == 'rms':
        v = p.mean()
    else:
        v = _slide(p, int((0.4 if mode == 'm' else 0.1) * SR)).max()
    return -0.691 + 10 * np.log10(max(v, 1e-20))


def momentary(x, a=0.0, b=None):
    """the loudest 400 ms block that lies between timeline a and b (LUFS)"""
    i, j = int(a * SR), int((b if b is not None else len(x) / SR) * SR)
    return lvl(x[max(i, 0):j], 'm')


def integrated(x):
    p = kpow(x)
    w, h = int(0.4 * SR), int(0.1 * SR)
    z = _slide(p, w)[::h]
    l = -0.691 + 10 * np.log10(np.maximum(z, 1e-20))
    z1 = z[l > -70]
    if not len(z1):
        return -120.0
    gate = -0.691 + 10 * np.log10(z1.mean()) - 10
    return float(-0.691 + 10 * np.log10(z[(l > -70) & (l > gate)].mean()))


def lra(x):
    p = kpow(x)
    z = _slide(p, int(3 * SR))[::int(0.1 * SR)]
    l = -0.691 + 10 * np.log10(np.maximum(z, 1e-20))
    l = l[l > -70]
    if not len(l):
        return 0.0
    gate = -0.691 + 10 * np.log10((10 ** ((l + 0.691) / 10)).mean()) - 20
    l = l[l > gate]
    return float(np.percentile(l, 95) - np.percentile(l, 10))


def true_peak(x):
    return float(db(np.abs(signal.resample_poly(st(x), 4, 1, axis=0)).max()))


def band_rms(x, lo, hi, a=None, b=None):
    """RMS (dBFS, both channels' mean power) of x in a band over timeline a..b"""
    y = st(x)[int((a or 0) * SR):int(b * SR) if b else None]
    sos = signal.butter(4, [lo, hi], 'bandpass', fs=SR, output='sos')
    return float(10 * np.log10(max((signal.sosfilt(sos, y, axis=0) ** 2).mean(), 1e-20)))


