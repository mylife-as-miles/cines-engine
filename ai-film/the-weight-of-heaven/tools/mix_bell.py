def get_ir():
    p = asset_path('hall_impulse')
    if p:
        ir = st(read_audio(p))
        return ir / np.sqrt((ir ** 2).sum(0).mean()), f"audio/sfx/{os.path.basename(p)} (unit energy, 90 ms pre-delay built in)"
    WARN.append("REVERB: asset 'hall_impulse' is missing; using stand-in (numpy cathedral impulse, 100 ms pre-delay)")
    return syn_hall(), 'numpy stand-in: synthetic cathedral impulse (RT60 about 6.5 s, 100 ms pre-delay)'


def reverb(send, ir):
    return np.stack([signal.fftconvolve(send[:, ch], ir[:, ch])[:N] for ch in range(2)], 1)


