def bed(cue, env_pts, ref, seed):
    x, _, label, standin = resolve(cue)
    x = st(x)
    if cue.get('excise') and not standin:                        # take events out of a loop (crossfaded), keep it a loop
        k = int(0.4 * SR)
        keep, t0 = [], 0.0
        for a, b in list(cue['excise']) + [(len(x) / SR, None)]:
            keep.append(x[int(t0 * SR):int(a * SR)])
            t0 = b
        y = keep[0]
        fa = np.sin(0.5 * np.pi * np.arange(k) / k)[:, None]
        for seg in keep[1:]:
            if len(seg) > 2 * k:
                y = np.concatenate([y[:-k], y[-k:] * np.sqrt(1 - fa ** 2) + seg[:k] * fa, seg[k:]])
        x = y
    if cue.get('noloop'):                                        # one pass from `start`, never repeated
        y = np.zeros((N + SR, 2))
        i = int(cue.get('start', 0.0) * SR)
        seg = fade(x, 0, 0.5)[:len(y) - i]
        y[i:i + len(seg)] = seg
        x = y
    reps = int(np.ceil((N + SR) / len(x)))
    if reps > 1:                                                 # loop-safe beds wrap; others get a 0.6 s crossfade
        k = int(0.6 * SR)
        if manifest().get(getattr(cue['src'][0], 'name', ''), {}).get('loop_safe') and not standin:
            x = np.concatenate([x] * reps)
        else:
            a = np.sin(0.5 * np.pi * np.arange(k) / k)[:, None]
            body = x[:len(x) - k].copy()
            body[:k] = x[:k] * a + x[len(x) - k:] * np.sqrt(1 - a ** 2)
            x = np.concatenate([body] * (reps + 1))
    x = eq(x[:N], cue.get('eq'))
    if cue.get('wind'):                                          # steady shaped noise reads as hiss: make it move like wind
        w = cue['wind']
        air = eq(x, [('hp', 2500, 2)])
        body = eq(x - air, [('hs', 1500, w['dark'])])
        low = _noise_band(N, seed + 60, 60, 400, -9.0, 2) * _slow(N, seed + 61, 0.35, 6.0)[:, None]
        body = body / np.sqrt((body ** 2).mean()) + w['low'] * low
        for k, (f_lo, f_hi, g) in enumerate(w['whistle']):       # the arches sing: narrow bands that glide
            body = body + g * _whistle(N, seed + 70 + k, f_lo, f_hi) * _slow(N, seed + 80 + k, 0.2, 6.0)[:, None]
        d, r = w['gust']
        gust = _slow(N, seed, r, d) * _slow(N, seed + 1, r * 3.1, d * 0.4)
        air = air / np.sqrt((air ** 2).mean()) * lin(w['air'])
        x = body * gust[:, None] + air * (gust ** 2.0)[:, None]  # the air moves more than the body does
    act = np.abs(x).max(1) > 0
    x *= lin(ref - lvl(x[act], 'rms'))
    return x * auto(env_pts)[:, None], label, standin


