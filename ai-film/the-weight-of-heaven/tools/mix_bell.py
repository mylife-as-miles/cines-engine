# ------------------------------------------------------------------------------------------ the master
def limiter(x, ceiling_db, lookahead=0.004, release=0.18):
    """a true-peak limiter: gain from the 4x oversampled peak, looking ahead, slow release. Returns (y, gain)."""
    c = lin(ceiling_db - 0.08)
    os4 = np.abs(signal.resample_poly(x, 4, 1, axis=0)).max(1)
    pk = os4[:len(x) * 4].reshape(len(x), 4).max(1)
    pk = np.maximum(pk, np.abs(x).max(1))
    pk = ndimage.maximum_filter1d(pk, 3)
    req = np.minimum(1.0, c / np.maximum(pk, 1e-12))
    if req.min() >= 1.0:
        return x.copy(), np.ones(len(x))
    L = int(lookahead * SR)
    g1 = ndimage.minimum_filter1d(req, L + 1, origin=-(L // 2))        # the minimum of the next L samples
    g1 = np.minimum(g1, ndimage.minimum_filter1d(req, 2 * L + 1))
    g2 = g1.copy()
    coef = np.exp(-1 / (release * SR))
    act = np.flatnonzero(g1 < 1.0)
    i, end = act[0], len(g1)
    prev = 1.0
    while i < end:                                               # release: back toward 1, slowly, only where needed
        v = 1 - (1 - prev) * coef
        cur = g1[i] if g1[i] < v else v
        g2[i] = cur
        prev = cur
        i += 1
        if cur > 0.99995 and i < end and g1[i] >= 1.0:
            nxt = act[np.searchsorted(act, i)] if np.searchsorted(act, i) < len(act) else end
            g2[i:nxt] = 1.0
            prev, i = 1.0, nxt
    g = ndimage.uniform_filter1d(g2, L, origin=(L // 2) - 1 if L > 2 else 0)
    g = np.minimum(g, 1.0)
    return x * g[:, None], g


def aac_roundtrip(wav, mp4=None, picture=None):
    """encode to AAC 256 k (muxed with the picture if given) and decode again -> the decoded samples"""
    out = mp4 or tempfile.mktemp(suffix='.m4a')
    if picture and mp4:
        cmd = ['ffmpeg', '-v', 'error', '-y', '-i', picture, '-i', wav, '-map', '0:v:0', '-map', '1:a:0', '-c:v', 'copy',
               '-c:a', 'aac', '-b:a', '256k', '-ar', str(SR), '-movflags', '+faststart', out]
    else:
        cmd = ['ffmpeg', '-v', 'error', '-y', '-i', wav, '-c:a', 'aac', '-b:a', '256k', '-ar', str(SR), out]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stderr[-2000:])
    d = subprocess.run(['ffmpeg', '-v', 'error', '-i', out, '-vn', '-ac', '2', '-ar', str(SR), '-f', 'f32le', '-'], capture_output=True)
    y = np.frombuffer(d.stdout, np.float32).reshape(-1, 2).astype(np.float64)
    if not mp4:
        os.remove(out)
    return y, out


def write_wav(path, x, subtype='PCM_24'):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    assert len(x) == N, len(x)
    sf.write(path, x, SR, subtype=subtype)


def master(stems, args):
    pre = sum(stems[s] for s in STEMS)
    m = {}
    ceiling = MAX_TP - 0.5
    gain = TARGET_I - integrated(pre)
    for _ in range(6):                                           # one gain to the target, measured after the limiter
        y, g = limiter(pre * lin(gain), ceiling)
        err = TARGET_I - integrated(y)
        if abs(err) < 0.03:
            break
        gain += err
    # stems are 24-bit files that sum to the pre-limiter mix: no stem may reach full scale. If that caps the gain, the
    # master lands that much under the loudness target (and the limiter works less).
    top = max(float(np.abs(stems[s]).max()) for s in STEMS) * lin(gain)
    cap = 0.0
    if top > lin(-0.02):
        cap = db(top) + 0.02
        gain -= cap
    m['gain_capped_by_stem_peak_db'] = round(cap, 2)
    out = args.out
    for attempt in range(5):                                     # the ceiling is lowered until the AAC decode is under MAX_TP
        y, g = limiter(pre * lin(gain), ceiling)
        write_wav(out, y)
        dec, mp4 = aac_roundtrip(out, None if args.no_mux else args.mux, None if args.no_mux else PICTURE)
        tp_aac = true_peak(dec)
        if tp_aac <= MAX_TP - 0.02:
            break
        ceiling -= (tp_aac - MAX_TP) + 0.1
    scaled = {s: stems[s] * lin(gain) for s in STEMS}
    m.update(gain_db=round(gain, 2), limiter_ceiling_dbtp=round(ceiling, 2), tp_after_aac=round(tp_aac, 2), mux=None if args.no_mux else mp4)
    return y, g, scaled, dec, m


