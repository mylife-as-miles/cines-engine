def build_dialogue(trim=None):
    """Q01's production sound on the film's clock (the 1.333 s cut out with a crossfade), each line at its level,
    the room held down between them. Returns (dry stereo, reverb send stereo, facts for the sheet)."""
    q = eq(take('Q01_t1').mean(1), Q01_EQ)
    xf = int(0.12 * SR)                                         # the join over the removed 1.333 s: equal power
    a_end = int(Q01_CUT[0] * SR) + xf // 2
    b_start = int(Q01_CUT[1] * SR) - xf // 2
    A_, B_ = q[:a_end].copy(), q[b_start:int((Q01_END + 0.05) * SR)].copy()
    A_[-xf:] *= np.cos(0.5 * np.pi * np.arange(xf) / xf)
    B_[:xf] *= np.sin(0.5 * np.pi * np.arange(xf) / xf)
    tr = np.zeros(N)
    i0 = int(round(T_NAVE * SR))
    tr[i0:i0 + len(A_)] += A_
    j0 = int(round(T_HIERO * SR)) - xf // 2
    tr[j0:j0 + len(B_)] += B_
    # levels: each line to its target by its own loudest 400 ms; the room a fixed amount under line 1's gain
    facts, pts, spts = {}, [(T_NAVE, None), (T_NAVE + 0.9, 0.0)], []
    gains = {}
    for cid, name, a, b, text in Q01_LINES:
        m = lvl(st(q[int(a * SR):int(b * SR)]), 'm')
        gains[cid] = (L_ANSWER if cid == 'DX-04' else L_LINE) - m + (trim or {}).get(cid, 0.0)
        facts[cid] = {'name': name, 'text': text, 'src': [a, b], 'timeline': [round(q01(a), 3), round(q01(b), 3)],
                      'take_m_lufs': round(m, 2), 'gain_db': round(gains[cid], 2)}
    room = gains['DX-02'] + ROOM_DB
    pts = [(T_NAVE, None), (T_NAVE + 0.9, room)]                 # the room fades up with the picture
    for cid, name, a, b, text in Q01_LINES:
        pts += [(q01(a) - 0.14, room), (q01(a), gains[cid]), (q01(b), gains[cid])]
        if cid != 'DX-04':
            pts.append((q01(b) + 0.22, room))
    t_end = q01(Q01_END)
    pts += [(t_end - 0.17, gains['DX-04']), (t_end, None)]       # out before the take's thump
    pts = sorted(pts, key=lambda p: p[0])
    env = auto(pts)
    dry = st(tr * env)
    # the answer comes from the galleries: its dry sound is spread; the Hierophant stays in the centre
    a0, a1 = int((q01(13.90) - 0.14) * SR), int(t_end * SR)
    w = widen(tr[a0:a1] * env[a0:a1], 0.75, 5)
    k = int(0.1 * SR)
    mixw = np.ones(a1 - a0)
    mixw[:k] = ramp(k)
    dry[a0:a1] = dry[a0:a1] * (1 - mixw[:, None]) + w * mixw[:, None]
    send_env = auto([(0, DX_SEND), (q01(13.90) - 0.15, DX_SEND), (q01(13.90), ANSWER_SEND), (DUR, ANSWER_SEND)])
    send = st(tr * env * send_env)
    facts['room_gain_db'] = round(room, 2)
    return dry, send, facts


