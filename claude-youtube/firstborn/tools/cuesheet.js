// Dump the video's named sound events for the Sound agent: node tools/cuesheet.js [out/cuesheet.json]
// Every sequence's cues (S.cue), beds (S.bed), ducks and silences, in seconds on the narration clock (= the video's clock),
// each cue with the spoken word nearest it (a spotting note: the cue is anchored to that word in the sequence's code).
// Also prints every cue and bed name in use with its count, so each can be mapped to a recording.
const { open } = require('./film');
(async () => {
  const out = process.argv[2] || 'out/cuesheet.json';
  const { browser, page, errs } = await open();
  const res = await page.evaluate(() => {
    const seqs = FILM.cuesheet();
    const ev = { about: 'Firstborn in an African Home: named sound cues on the narration clock (seconds); x = the source across the frame (0 left, 0.5 centre, 1 right; UI and graphic cues 0.5). Generated by tools/cuesheet.js from film/seq/*.js.',
      total: FILM.total, fps: FILM.FPS, narration: 'out/vo/narration.wav', narration_end: FILM.words.length ? FILM.words[FILM.words.length - 1].t1 : null,
      seqs: seqs.map(s => ({ id: s.id, title: s.title, chapter: s.chapter, start: +s.start.toFixed(3), end: +s.end.toFixed(3) })), cues: [], beds: [], ducks: [], silences: [] };
    const r3 = v => +(+v).toFixed(3);
    for (const s of seqs) {
      for (const c of s.cues) ev.cues.push({ t: r3(c.t), name: c.name, seq: s.id, x: c.x, word: c.word, word_t: c.word_t != null ? r3(c.word_t) : null, p: c.p });
      for (const b of s.beds) ev.beds.push({ t0: r3(b.t0), t1: r3(b.t1), name: b.name, seq: s.id, p: b.p });
      for (const d of s.ducks) ev.ducks.push({ t0: r3(d.t0), t1: r3(d.t1), level: d.level, seq: s.id });
      for (const x of s.silences) ev.silences.push({ t0: r3(x.t0), t1: r3(x.t1), seq: s.id });
    }
    ev.cues.sort((a, b) => a.t - b.t); ev.beds.sort((a, b) => a.t0 - b.t0);
    return { ev, warnings: FILM.warnings };
  });
  const ev = res.ev;
  require('fs').writeFileSync(out, JSON.stringify(ev, null, 1));
  const count = (arr) => arr.reduce((m, e) => (m[e.name] = (m[e.name] || 0) + 1, m), {});
  console.log(`video ${ev.total} s, ${ev.seqs.length} sequences; ${ev.cues.length} cues, ${ev.beds.length} beds, ${ev.ducks.length} ducks, ${ev.silences.length} silences -> ${out}`);
  console.log('cues: ' + Object.entries(count(ev.cues)).sort().map(([k, v]) => `${k}(${v})`).join(' '));
  console.log('beds: ' + Object.entries(count(ev.beds)).sort().map(([k, v]) => `${k}(${v})`).join(' '));
  if (res.warnings.length) console.log('warnings:\n  ' + res.warnings.join('\n  '));
  const u = [...new Set(errs)].filter(e => !/\[film\]/.test(e)); if (u.length) console.log(u.slice(0, 10).join('\n'));
  await browser.close();
})();
