// Shared headless page for the film tools, and the narration data the page reads.
//   require('./film').open(opts) -> { browser, page, errs }   (film/headless.html with every sequence loaded)
//   node tools/film.js sync      -> rebuild film/words.js (from audio/vo/words.json) and film/vo_env.js (from out/vo/narration.wav)
// The page cannot fetch JSON from file://, so the word times and the loudness envelope are served as small scripts. open()
// rebuilds them whenever their source is newer, so a re-timed take re-times every tool's render without a manual step.
const path = require('path'); const fs = require('fs'); const { execFileSync } = require('child_process');
const ROOT = path.resolve(__dirname, '..');
const WORDS = path.join(ROOT, 'audio/vo/words.json'), WORDS_JS = path.join(ROOT, 'film/words.js');
const WAV = path.join(ROOT, 'out/vo/narration.wav'), ENV_JS = path.join(ROOT, 'film/vo_env.js');
const newer = (a, b) => fs.existsSync(a) && (!fs.existsSync(b) || fs.statSync(a).mtimeMs > fs.statSync(b).mtimeMs);

function syncWords(force) {
  if (!force && !newer(WORDS, WORDS_JS)) return false;
  const d = JSON.parse(fs.readFileSync(WORDS, 'utf8'));
  const words = d.words.map(w => ({ w: w.w, t0: +(+w.t0).toFixed(3), t1: +(+w.t1).toFixed(3) }));
  fs.writeFileSync(WORDS_JS, '/* generated by tools/film.js from audio/vo/words.json (the narration clock). Do not edit. */\n' +
    'window.FILM_WORDS = ' + JSON.stringify({ source: 'audio/vo/words.json', words }) + ';\n');
  return true;
}
// the narration's loudness at 48 Hz (RMS over 1/24 s), mapped -50..-5 dBFS to 0..61 and stored one character per sample
function syncEnv(force) {
  if (!force && !newer(WAV, ENV_JS)) return false;
  const SR = 8000, HZ = 48;
  const raw = execFileSync('ffmpeg', ['-v', 'error', '-i', WAV, '-ac', '1', '-ar', String(SR), '-f', 's16le', '-'], { maxBuffer: 64 << 20 });
  const n = raw.length >> 1, hop = SR / HZ, win = SR / 24; let s = '';
  for (let i = 0; i * hop < n; i++) {
    const c = Math.round(i * hop), a = Math.max(0, Math.round(c - win / 2)), b = Math.min(n, Math.round(c + win / 2)); let e = 0;
    for (let k = a; k < b; k++) { const v = raw.readInt16LE(k * 2) / 32768; e += v * v; }
    const db = 10 * Math.log10(e / Math.max(1, b - a) + 1e-12); const v = Math.max(0, Math.min(1, (db + 50) / 45));
    s += String.fromCharCode(48 + Math.round(v * 61));
  }
  fs.writeFileSync(ENV_JS, '/* generated by tools/film.js from out/vo/narration.wav: loudness at 48 Hz, (code-48)/61 = 0..1 over -50..-5 dBFS. */\n' +
    'window.FILM_VOENV = ' + JSON.stringify({ hz: HZ, data: s }) + ';\n');
  return true;
}
function sync(force) { const a = syncWords(force), b = syncEnv(force); return { words: a, env: b }; }

async function open(opts) {
  opts = opts || {}; sync(false);
  const { chromium } = require('playwright');
  const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
  const page = await browser.newPage({ viewport: { width: opts.w || 1920, height: opts.h || 1080 }, deviceScaleFactor: 1 });
  const errs = [];
  page.on('pageerror', e => errs.push('pageerror: ' + e.message));
  page.on('console', m => { if ((m.type() === 'error' || m.type() === 'warning') && !/willReadFrequently/.test(m.text())) errs.push(m.type() + ': ' + m.text()); });
  await page.goto('file://' + path.join(ROOT, 'film/headless.html') + (opts.placeholders || process.argv.includes('--placeholders') ? '?placeholders=1' : ''));
  await page.waitForFunction(() => window.FILM_READY === true, null, { timeout: 60000 });
  return { browser, page, errs };
}
module.exports = { open, sync, ROOT };

if (require.main === module) {
  const cmd = process.argv[2];
  if (cmd === 'sync') { const r = sync(process.argv.includes('--force')); console.log('words.js ' + (r.words ? 'rebuilt' : 'up to date') + ', vo_env.js ' + (r.env ? 'rebuilt' : 'up to date')); }
  else console.log('usage: node tools/film.js sync [--force]');
}
